/** 상태별 개수 — 화면 맨 위 숫자 카드가 읽는다 */
export function countByStatus(list: Idea[] = IDEAS): Record<IdeaStatus, number> {
  const out = { live: 0, draft: 0, ready: 0, paused: 0, dropped: 0 } as Record<IdeaStatus, number>;
  for (const i of list) out[i.status] += 1;
  return out;
}

/**
 * 검색 — **제목·내용·코드 번호** 전부를 본다(대표님 지시).
 * ★ 숫자만 치셔도 찾는다. 「3」 → idea-00003. 대화에서 「3번 그거」라고 부르시기 때문이다.
 * ⚠ 앞의 0 을 빼고 치셔도(「3」) 붙여 치셔도(「00003」) 같게 나오게 숫자로 견준다.
 */
export function matchIdea(idea: Idea, q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  if (/^\d+$/.test(needle)) {
    const n = Number(idea.code.replace(/\D/g, ""));
    if (n === Number(needle)) return true;
  }
  const hay = [
    idea.code,
    idea.title,
    idea.summary,
    idea.tokenCost,
    idea.plan,
    IDEA_STATUS[idea.status].label,
    ...idea.pros,
    ...idea.cons,
  ]
    .join(" ")
    .toLowerCase();
  return hay.includes(needle);
}

/**
 * 다음에 쓸 번호. 🔴 **가장 큰 번호 + 1** 이다 — 개수 + 1 이 아니다.
 * 폐기된 아이디어의 번호를 되쓰면 옛 대화(「7번 폐기했잖아」)가 새 아이디어를 가리키게 된다.
 */
export function nextIdeaCode(list: Idea[] = IDEAS): string {
  const max = list.reduce((m, i) => Math.max(m, Number(i.code.replace(/\D/g, "")) || 0), 0);
  return `idea-${String(max + 1).padStart(5, "0")}`;
}
