export type CustomProduct = {
  id: string;
  /** 상품 이름 */
  name: string;
  /** 원 단위. 부가세 **포함** 금액이다 */
  price: number;
  /** 무엇을 해 드리나 — 한 줄 */
  what: string;
  /** 제공 기간(영업일) */
  days: number;
};

