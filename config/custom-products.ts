/** 화면에 찍는 금액 한 줄 — 세 자리마다 쉼표를 넣고 「원」을 붙인다 */
export const priceLabel = (p: CustomProduct) => `${p.price.toLocaleString("ko-KR")}원`;

/** 제공 기간 한 줄 — 「영업일 2일」 */
export const daysLabel = (p: CustomProduct) => `영업일 ${p.days}일`;

