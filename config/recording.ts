/**
 * 60초 녹화의 스위치 — **단일 출처.** (2026-09-17 대표님 제보로 신설)
 *
 * ★★ 대표님 원문: 「분명히 크롬으로 세로모드로 했는데 찍고 나서 보면 가로로 찍혔다고 나와.
 *   2-3번 해봐도 그래. 정말 신기한 건, 가로로 찍으니 세로로 저장되네?」
 *
 * ★★ **왜 «부탁»으로는 못 고치나.** `getUserMedia` 의 `width/height/aspectRatio` 는 전부
 *   `ideal`(부탁)이다. 기기가 들어줄 수도, 안 들어줄 수도 있다. 더 나쁜 것은 —
 *   🔴 **찍는 도중에 폰을 돌리면 스트림 해상도가 «실제로» 바뀐다.** 안드로이드 크롬은
 *   720×1280 ↔ 1280×720 으로 갈아타고, `MediaRecorder` 는 바뀐 크기를 그대로 받아 적는다.
 *   ⇒ 대표님이 「흔들면서 찍으니 가로로 찍혔다」고 하신 것이 정확히 이것이다.
 *
 * ⇒ **우리가 직접 그린다.** 카메라 그림을 «고정 크기 캔버스»에 9:16 으로 잘라 그리고,
 *   그 **캔버스를** 녹화한다. 캔버스 크기는 절대 안 바뀌므로 결과도 절대 안 바뀐다.
 */

/**
 * 녹화를 «캔버스 중계»로 할까.
 *
 * ⚠ 끄면 **예전(카메라 스트림 직접 녹화)으로 정확히 돌아간다.** 느린 폰에서 문제가 생기면
 *   이 값 하나로 되돌린다 — 배포 없이 바꾸려면 아래 환경변수를 쓴다.
 * ⚠ **소리만 녹음(audio)에는 적용되지 않는다.** 그림이 없는데 캔버스를 태울 이유가 없다.
 */
export const CANVAS_RELAY: boolean =
  !/^(off|false|0)$/i.test((process.env.NEXT_PUBLIC_RECORDING_CANVAS_RELAY ?? "").trim());

/**
 * 캔버스 크기 — **9:16 고정.**
 *
 * ⚠ 720×1280 이 안 나오는 폰(프레임이 밀리는 폰)이 있으면 **540×960 으로 낮춰라.**
 *   릴스·틱톡의 최소 기준(540×960)을 여전히 넘는다. 화질보다 «안 끊기는 것»이 먼저다.
 * ⚠ 이 둘의 비율을 9:16 이 아닌 값으로 바꾸지 마라 — 자르는 계산이 이 비율을 전제로 한다.
 */
export const RELAY_W = 720;
export const RELAY_H = 1280;

/** 캔버스를 초당 몇 장 내보낼까. 30 이면 릴스·쇼츠·틱톡 모두 충분하다 */
export const RELAY_FPS = 30;

/**
 * 실제로 몇 장을 그렸는지 재서 로그에 남길까.
 * ⚠ 권반장 지시 — 「느린 폰에서 프레임이 밀리는지 보십시오」. 사람이 눈으로 세지 않으려면
 *   기계가 재야 한다. 이 값이 20 아래로 자주 나오면 캔버스를 540×960 으로 낮춘다.
 */
export const RELAY_MEASURE = true;

/**
 * 🔴🔴 **영상 초당 비트 — «환경변수로 고를 수 있게» 빼 둔 곳.** (2026-09-18 지시 [51]①)
 *
 * ## 왜 이 파일로 왔나 — 숫자가 «화면 크기와 어긋나 있었다»
 * ```
 * 9/10~11  720×1280 · 2.1~2.5Mbps  ⇒ 60초 환산 15.6~21.0MB
 * 9/12~16  2052×1154(가로로 찍히던 때) · 6.0~7.45Mbps ⇒ 43.8~54.1MB
 * 🔴 9/17~ 720×1280(캔버스 중계로 고침) · 5.86Mbps    ⇒ 42.7MB   ← 화면은 2.6배 작아졌는데 그대로다
 * ```
 * ⇒ [16] 이 «화면 크기»는 고쳤는데 **비트는 1080 시절 값(6Mbps)이 남아 있었다.**
 *   `RELAY_W`·`RELAY_H` 바로 옆에 두어 **둘이 어긋나면 눈에 보이게** 한다.
 *
 * ## 🔴 기본값은 «지금 그대로 6,000,000» 이다. 바꾸지 마라
 * **화질은 대표님 눈으로만 판정된다.** 이 지시는 «고를 수 있게 만드는 것»까지다.
 * 대표님이 Vercel 에서 `NEXT_PUBLIC_RECORDING_VIDEO_BPS` 숫자만 바꿔 가며 폰으로 비교하신다.
 * ⇒ **숫자를 바꿀 때마다 «코드»를 고치고 커밋하지 않아도 된다**는 것이 값어치다(B-13 과 같은 뜻).
 *
 * 🔴🔴 **다만 «배포 없이» 바뀌는 것은 아니다 — 권반장 정정(2026-09-18).**
 *   `NEXT_PUBLIC_*` 은 **만들 때(빌드) 코드 안에 글자로 박힌다.** Vercel 에서 값만 고치고 두면
 *   **손님·사장님 화면은 옛 숫자 그대로**다. ⇒ 값을 바꾼 뒤 **[Redeploy] 를 한 번 눌러야** 한다.
 *   ⚠ 이 사실을 모르면 「바꿨는데 왜 그대로지?」로 한나절을 버린다. 그래서 여기 적어 둔다.
 *
 * | 설정 | 60초 환산 | 몇 분의 일 |
 * |---|---|---|
 * | `6000000`(지금) | 약 42.7MB | — |
 * | `3000000` | 약 23MB | 1/1.9 |
 * | `1500000` | 약 12MB | 1/3.5 |
 * | `1000000` | 약 8.5MB | 1/5 |
 *
 * ⚠⚠ **이 값은 «상한»이 아니라 «부탁»이다.** W3C 규격에 "might be surpassed" 라고 적혀 있고,
 *   실측도 그렇다(요청 6.0 → 7.45Mbps · 안드로이드는 +37% 까지). 그래서 **낮춰도 그대로 안 나온다.**
 *   진짜로 믿을 수 있는 손잡이는 **해상도**(`RELAY_W`·`RELAY_H`)다.
 * ⚠ **범위 밖이거나 못 읽는 값이면 조용히 기본값**이다 — 오타 하나로 녹화가 죽으면 안 된다.
 *   0.3~20Mbps 밖은 받지 않는다(너무 낮으면 못 볼 화질, 너무 높으면 폰 저장소가 터진다).
 */
export const VIDEO_BPS: number = (() => {
  const n = Number((process.env.NEXT_PUBLIC_RECORDING_VIDEO_BPS ?? "").trim());
  return Number.isFinite(n) && n >= 300_000 && n <= 20_000_000 ? Math.round(n) : 6_000_000;
})();
