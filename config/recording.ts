/**
 * 60초 녹화의 스위치 — **단일 출처.** (2026-09-17 대표님 제보로 신설)
 *
 * ★★ 대표님 원문: 「분명히 크롬으로 세로모드로 했는데 찍고 나서 보면 가로로 찍혔다고 나와.
 *   2-3번 해봐도 그래. 정말 신기한 건, 가로로 찍으니 세로로 저장되네?」
 *
 * ★★ **왜 «부탁»으로는 못 고치나.** `getUserMedia` 의 `width/height/aspectRatio` 는 전부
 *   `ideal`(부탁)이다. 기기가 들어줄 수도, 안 들어줄 수도 있다. 더 나쁜 것은 —
 *   🔴 **찍는 도중에 폰을 돌리면 스트림 해상도가 «실제로» 바뀐다.** 안드로이드 크롬은
 *   720×1280 ↔ 1280×720 으로 갈아타고, `MediaRecorder` 는 바뀐 크기를 그대로 받아 적는다.
 *   ⇒ 대표님이 「흔들면서 찍으니 가로로 찍혔다」고 하신 것이 정확히 이것이다.
 *
 * ⇒ **우리가 직접 그린다.** 카메라 그림을 «고정 크기 캔버스»에 9:16 으로 잘라 그리고,
 *   그 **캔버스를** 녹화한다. 캔버스 크기는 절대 안 바뀌므로 결과도 절대 안 바뀐다.
 */

/**
 * 녹화를 «캔버스 중계»로 할까.
 *
 * ⚠ 끄면 **예전(카메라 스트림 직접 녹화)으로 정확히 돌아간다.** 느린 폰에서 문제가 생기면
 *   이 값 하나로 되돌린다 — 배포 없이 바꾸려면 아래 환경변수를 쓴다.
 * ⚠ **소리만 녹음(audio)에는 적용되지 않는다.** 그림이 없는데 캔버스를 태울 이유가 없다.
 */
export const CANVAS_RELAY: boolean =
  !/^(off|false|0)$/i.test((process.env.NEXT_PUBLIC_RECORDING_CANVAS_RELAY ?? "").trim());

/**
 * 캔버스 크기 — **9:16 고정.**
 *
 * ⚠ 720×1280 이 안 나오는 폰(프레임이 밀리는 폰)이 있으면 **540×960 으로 낮춰라.**
 *   릴스·틱톡의 최소 기준(540×960)을 여전히 넘는다. 화질보다 «안 끊기는 것»이 먼저다.
 * ⚠ 이 둘의 비율을 9:16 이 아닌 값으로 바꾸지 마라 — 자르는 계산이 이 비율을 전제로 한다.
 */
export const RELAY_W = 720;
export const RELAY_H = 1280;

/** 캔버스를 초당 몇 장 내보낼까. 30 이면 릴스·쇼츠·틱톡 모두 충분하다 */
export const RELAY_FPS = 30;

/**
 * 실제로 몇 장을 그렸는지 재서 로그에 남길까.
 * ⚠ 권반장 지시 — 「느린 폰에서 프레임이 밀리는지 보십시오」. 사람이 눈으로 세지 않으려면
 *   기계가 재야 한다. 이 값이 20 아래로 자주 나오면 캔버스를 540×960 으로 낮춘다.
 */
export const RELAY_MEASURE = true;
