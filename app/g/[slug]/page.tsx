import { permanentRedirect } from "next/navigation";

/**
 * ★★★ **`/g/{상호}` 는 폐기됐다. `/{상호}` 로 영구 이동한다.** (2026-09-15 대표님 지시)
 *
 * ★ 왜 없앴나 — 대표님 말씀 그대로:
 *   「홈페이지 새로 만들어도 `/g/` 라는 곳으로 가는 게 아니라 **그냥 홈페이지가 오픈되게** 만들어.
 *    `/g/` 및 「견본입니다」 부분, 제거해. **이런 거 넣지 마.**」
 *
 *   `/g/` 는 「미리 만든 견본이 그 가게 상호로 검색에 뜨면 안 된다」는 걱정에서 나온
 *   **시키지 않은 안전장치**였다. 그런데 그 판정이 문자 자물쇠(`isPremade`)와 묶여 있어서
 *   **대표님이 만드신 홈페이지가 `/{상호}` 에서 안 열렸다.** 09-15 에 `onstori.com/feliz` 를
 *   못 만드신 것이 그 때문이다. 걱정보다 손해가 컸다.
 *
 * ★ **왜 파일을 지우지 않고 이동만 남겼나.**
 *   대표님이 이미 `/g/{상호}` 주소를 영업에 보내 두셨을 수 있다. 파일을 지우면 그 링크가
 *   **404** 가 된다. 이동만 남기면 **옛 링크가 그대로 살아서** 새 주소로 간다. 비용은 0 이다.
 *
 * ⚠ 검색은 원래 주소(`/{상호}`)를 기준으로 삼는다 — `permanentRedirect`(308) 가 그렇게 알린다.
 * ⚠ 이 파일은 «껍데기»다. 여기에 조건을 다시 넣지 마라. 보여 줄지 말지는 `lib/sites.ts` 한 곳이 정한다.
 */
export default async function GoneGroupPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  permanentRedirect(`/${slug}`);
}
